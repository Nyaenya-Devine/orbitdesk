export function getTranslation(lang: Language, key: string): string {
  const trans = translations[lang] || translations.en;
  return (trans as any)[key] || (translations.en as any)[key] || key;
}

export function detectLanguage(): Language {
  if (typeof window === 'undefined') return 'en';
  const saved = localStorage.getItem('orbitdesk_language') as Language;
  if (saved && languages[saved]) return saved;
  
  const browserLang = navigator.language.split('-')[0] as Language;
  if (languages[browserLang]) return browserLang;
  
  // Check for Swahili browser or Kenya
  if (navigator.language.toLowerCase().includes('sw') || Intl.DateTimeFormat().resolvedOptions().timeZone.includes('Nairobi')) {
    return 'sw';
  }
  
  return 'en';
}

export function setLanguage(lang: Language) {
  if (typeof window !== 'undefined') {
    localStorage.setItem('orbitdesk_language', lang);
    document.documentElement.lang = lang;
    if (lang === 'ar') {
      document.documentElement.dir = 'rtl';
    } else {
      document.documentElement.dir = 'ltr';
    }
  }
}
